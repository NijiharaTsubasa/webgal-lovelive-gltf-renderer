export function readMotionSourceId(text) {
  const tags = [...text.matchAll(/^[\t ]*PARAM_IMPORT[\t ]*=[\t ]*([^\r\n]*)/gm)];
  if (tags.length !== 1) return null;
  const value = tags[0][1].trim();
  if (!/^[+-]?\d+$/.test(value)) return null;
  const id = Number(value);
  return Number.isSafeInteger(id) ? id : null;
}

export function sourceEyeOpenMaximum(sourceId) {
  const curve = SOURCE_CURVES[sourceId]?.L[0];
  return curve ? OPEN_NODES[curve.length - 1] : null;
}

function sampleOpen(curve, open) {
  const last = curve.length - 1;
  if (open <= OPEN_NODES[0]) return curve[0];
  if (open >= OPEN_NODES[last]) return curve[last];
  const upper = OPEN_NODES.findIndex((node) => node >= open);
  const lower = upper - 1;
  const amount = (open - OPEN_NODES[lower]) / (OPEN_NODES[upper] - OPEN_NODES[lower]);
  return curve[lower] + (curve[upper] - curve[lower]) * amount;
}

export function sourceEyeOpen(sourceId, side, open, smile) {
  const curves = SOURCE_CURVES[sourceId]?.[side];
  if (!curves) return open;
  if (curves.length === 1) return sampleOpen(curves[0], open);

  const position = Math.min(1, Math.max(0, smile)) * 2;
  const lower = Math.min(1, Math.floor(position));
  const amount = position - lower;
  const from = sampleOpen(curves[lower], open);
  const to = sampleOpen(curves[lower + 1], open);
  return from + (to - from) * amount;
}
